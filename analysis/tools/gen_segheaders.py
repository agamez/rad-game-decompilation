#!/usr/bin/env python3
# gen_segheaders.py -- emit src/seg<seg>.h from analysis/summary/iface.tsv.
#
# One include-guarded header per original code segment, containing the
# canonical prototype of every function in that segment (deterministic order,
# by function offset).  These headers are the cross-segment call contract.
#
# stdlib only.

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reko_common as rc  # noqa: E402

IFACE_PATH = os.path.join(rc.SUMMARY_DIR, "iface.tsv")

# The 14 code segments of RAD.EXE (DGROUP 2014 has no functions).
SEGMENTS = [
    "0800", "0C43", "0C74", "11C8", "1206", "1229", "133F",
    "13C1", "13C8", "13E2", "1AB8", "1E5F", "1E78", "1EDA",
]


def read_iface():
    rows = {}
    with open(IFACE_PATH, "r", encoding="utf-8") as fh:
        for i, line in enumerate(fh):
            if i == 0 or not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            seg, func, proto = parts[0], parts[1], parts[2]
            rows.setdefault(seg, []).append((func, proto))
    return rows


def main():
    rows = read_iface()
    for seg in SEGMENTS:
        entries = sorted(rows.get(seg, []), key=lambda x: int(x[0], 16))
        guard = "SEG%s_H" % seg
        lines = [
            "/* seg%s.h -- canonical prototypes for segment %s." % (seg, seg),
            " * Generated by analysis/tools/gen_segheaders.py from",
            " * analysis/summary/iface.tsv -- do not edit by hand. */",
            "#ifndef %s" % guard,
            "#define %s" % guard,
            "",
            '#include "radtypes.h"',
            "",
        ]
        for _func, proto in entries:
            lines.append("extern %s;" % proto)
        lines += ["", "#endif /* %s */" % guard, ""]
        path = os.path.join(rc.SRC_DIR, "seg%s.h" % seg)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
        print("wrote %s (%d prototypes)" % (path, len(entries)))


if __name__ == "__main__":
    main()
