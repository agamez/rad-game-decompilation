#!/usr/bin/env python3
# summarize.py -- write analysis/summary/REPORT.md.
#
# Project-wide and per-segment summary of the recovered code: function counts,
# code bytes, hardware touchpoints, string literals and the largest functions.
# See analysis/tools/README.md.

import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import reko_common as rc  # noqa: E402

MAX_STRINGS = 20
MAX_FUNCS = 10


def collect_strings(seg):
    out = []
    seen = set()

    def add_all(items):
        for s in items:
            if s not in seen:
                seen.add(s)
                out.append(s)

    asm_path = os.path.join(rc.REKO_DIR, "RAD_%s.asm" % seg)
    if os.path.exists(asm_path):
        add_all(rc.extract_strings_from_asm(rc.read_lines(asm_path)))
    for ext in (".c", ".dis"):
        path = os.path.join(rc.REKO_DIR, "RAD_%s%s" % (seg, ext))
        if os.path.exists(path):
            add_all(rc.extract_strings_from_c(rc.read_lines(path)))
    return out


def main():
    rc.ensure_dir(rc.SUMMARY_DIR)
    cfuncs = rc.parse_c_functions()
    afuncs = rc.parse_asm_functions()

    total_funcs = 0
    total_bytes = 0
    total_c_lines = 0
    for seg in rc.segment_ids():
        total_funcs += len(cfuncs.get(seg, []))
        total_bytes += sum(e["size"] for e in afuncs.get(seg, []))
        total_c_lines += len(rc.read_lines(os.path.join(rc.REKO_DIR, "RAD_%s.c" % seg)))

    lines = []
    lines.append("# RAD V3.1 decompilation summary")
    lines.append("")
    lines.append("Generated by `analysis/tools/summarize.py`.")
    lines.append("")
    lines.append("## Project totals")
    lines.append("")
    lines.append("- functions: %d" % total_funcs)
    lines.append("- total code bytes: %d" % total_bytes)
    lines.append("- total C lines (RAD_*.c): %d" % total_c_lines)
    lines.append("")
    lines.append("## Per segment")
    lines.append("")

    for seg in rc.segment_ids():
        entries = afuncs.get(seg, [])
        centries = cfuncs.get(seg, [])
        seg_bytes = sum(e["size"] for e in entries)

        touch = Counter()
        for e in entries:
            touch.update(e["direct_touches"])

        strings = collect_strings(seg)

        largest = sorted(entries, key=lambda e: (-e["size"], e["func"]))[:MAX_FUNCS]

        lines.append("### Segment %s" % seg)
        lines.append("")
        lines.append("- functions: %d" % len(centries))
        lines.append("- code bytes: %d" % seg_bytes)
        if touch:
            parts = []
            for tok in sorted(touch, key=rc.touch_sort_key):
                parts.append("%s x%d" % (tok, touch[tok]))
            lines.append("- hardware touchpoints: " + ", ".join(parts))
        else:
            lines.append("- hardware touchpoints: (none)")
        if strings:
            shown = ["`%s`" % s for s in strings[:MAX_STRINGS]]
            extra = len(strings) - len(shown)
            text = ", ".join(shown)
            if extra > 0:
                text += " (+%d more)" % extra
            lines.append("- strings (%d): %s" % (len(strings), text))
        else:
            lines.append("- strings (0): (none)")
        lines.append("- largest functions:")
        lines.append("")
        lines.append("  | function | bytes | C lines |")
        lines.append("  | --- | ---: | ---: |")
        by_name = {e["func"]: e for e in entries}
        for e in largest:
            cl = 0
            for cf in centries:
                if int(cf["func"], 16) == e["func"]:
                    cl = cf["c_line_count"]
                    break
            lines.append("  | %s | %d | %d |" % (e["name"], e["size"], cl))
        lines.append("")

    out_path = os.path.join(rc.SUMMARY_DIR, "REPORT.md")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s (%d functions, %d bytes)" % (out_path, total_funcs, total_bytes))


if __name__ == "__main__":
    main()
